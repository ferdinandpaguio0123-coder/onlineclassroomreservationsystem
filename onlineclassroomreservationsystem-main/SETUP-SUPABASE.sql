-- ClassReserve database setup. Review your existing tables before running.
-- This assumes public.profiles has id (uuid), username (text), and role (text),
-- and that each profile id matches its Supabase Auth user id.

alter table public.reservations add column if not exists user_id uuid references auth.users(id) on delete cascade;

create table if not exists public.reservation_history (
  id bigint generated by default as identity primary key,
  reservation_id bigint not null references public.reservations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  classroom text not null,
  changed_by uuid references auth.users(id),
  old_status text,
  new_status text not null,
  changed_at timestamptz not null default now()
);

alter table public.reservations enable row level security;
alter table public.reservation_history enable row level security;

-- Remove prior policies with these names so this script can be run again.
drop policy if exists "classreserve read own or admin reservations" on public.reservations;
drop policy if exists "classreserve insert own pending reservations" on public.reservations;
drop policy if exists "classreserve admin update reservations" on public.reservations;
drop policy if exists "classreserve read own or admin history" on public.reservation_history;

create policy "classreserve read own or admin reservations" on public.reservations
for select to authenticated using (
  user_id = auth.uid() or exists (select 1 from public.profiles p where p.id = auth.uid() and lower(p.role) = 'admin')
);
create policy "classreserve insert own pending reservations" on public.reservations
for insert to authenticated with check (
  user_id = auth.uid() and status = 'Pending'
  and exists (select 1 from public.profiles p where p.id = auth.uid() and lower(p.role) in ('student','faculty'))
);
create policy "classreserve admin update reservations" on public.reservations
for update to authenticated using (
  exists (select 1 from public.profiles p where p.id = auth.uid() and lower(p.role) = 'admin')
) with check (
  exists (select 1 from public.profiles p where p.id = auth.uid() and lower(p.role) = 'admin')
);
create policy "classreserve read own or admin history" on public.reservation_history
for select to authenticated using (
  user_id = auth.uid() or exists (select 1 from public.profiles p where p.id = auth.uid() and lower(p.role) = 'admin')
);

create or replace function public.classreserve_log_reservation_change()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if TG_OP = 'INSERT' then
    insert into public.reservation_history(reservation_id,user_id,username,classroom,changed_by,old_status,new_status)
    values(new.id,new.user_id,new.username,new.classroom,auth.uid(),null,new.status);
    return new;
  elsif old.status is distinct from new.status then
    insert into public.reservation_history(reservation_id,user_id,username,classroom,changed_by,old_status,new_status)
    values(new.id,new.user_id,new.username,new.classroom,auth.uid(),old.status,new.status);
  end if;
  return new;
end; $$;

drop trigger if exists classreserve_reservation_history_trigger on public.reservations;
create trigger classreserve_reservation_history_trigger
after insert or update of status on public.reservations
for each row execute function public.classreserve_log_reservation_change();

grant select, insert, update on public.reservations to authenticated;
grant select on public.reservation_history to authenticated;
grant usage, select on sequence public.reservation_history_id_seq to authenticated;
